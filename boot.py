import board
import digitalio
import storage
import supervisor
import usb_cdc
import usb_hid
import usb_midi

# Short GP15 and ground to access the file partition in PC
pin = digitalio.DigitalInOut(board.GP15)
pin.switch_to_input(pull=digitalio.Pull.UP)

if pin.value:
    supervisor.set_usb_identification(vid=0x0F0D, pid=0x0092)

    storage.disable_usb_drive()
    usb_cdc.disable()
    usb_midi.disable()

    SWITCH_GAMEPAD_DESCRIPTOR = bytes((
        0x05, 0x01, 0x09, 0x05, 0xA1, 0x01, 0x15, 0x00,
        0x25, 0x01, 0x35, 0x00, 0x45, 0x01, 0x75, 0x01,
        0x95, 0x10, 0x05, 0x09, 0x19, 0x01, 0x29, 0x10,
        0x81, 0x02, 0x05, 0x01, 0x25, 0x07, 0x46, 0x3B,
        0x01, 0x75, 0x04, 0x95, 0x01, 0x65, 0x14, 0x09,
        0x39, 0x81, 0x42, 0x65, 0x00, 0x95, 0x01, 0x81,
        0x01, 0x26, 0xFF, 0x00, 0x46, 0xFF, 0x00, 0x09,
        0x30, 0x09, 0x31, 0x09, 0x32, 0x09, 0x35, 0x75,
        0x08, 0x95, 0x04, 0x81, 0x02, 0x06, 0x00, 0xFF,
        0x09, 0x20, 0x95, 0x01, 0x81, 0x02, 0x0A, 0x21,
        0x26, 0x95, 0x08, 0x91, 0x02, 0xC0
    ))

    gamepad = usb_hid.Device(
        report_descriptor=SWITCH_GAMEPAD_DESCRIPTOR,
        usage_page=0x01,
        usage=0x05,
        report_ids=(0,),
        in_report_lengths=(8,),
        out_report_lengths=(8,),
    )
    usb_hid.enable((gamepad,))